// Bundles templates/laravel/<id>/ into src/lib/laravel-templates.generated.ts so the Laravel tab can offer them as starting points.
// Everything except template.json and web/ is a project file; web/ is the matching HTML/CSS/JS test client.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "templates", "laravel");

function walk(base, rel = "") {
  const out = {};
  for (const name of fs.readdirSync(path.join(base, rel)).sort()) {
    const r = rel ? `${rel}/${name}` : name;
    if (fs.statSync(path.join(base, r)).isDirectory()) Object.assign(out, walk(base, r));
    else out[r] = fs.readFileSync(path.join(base, r), "utf8");
  }
  return out;
}

const templates = fs.readdirSync(dir).filter((d) => fs.existsSync(path.join(dir, d, "template.json"))).map((id) => {
  const meta = JSON.parse(fs.readFileSync(path.join(dir, id, "template.json"), "utf8"));
  const all = walk(path.join(dir, id));
  const web = { html: all["web/index.html"] ?? "", css: all["web/style.css"] ?? "", js: all["web/app.js"] ?? "" };
  const files = Object.fromEntries(Object.entries(all).filter(([p]) => p !== "template.json" && !p.startsWith("web/")));
  return { ...meta, files, web };
}).sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

const header = "// Generated by scripts/build-laravel-templates.mjs from templates/laravel. Do not edit by hand.\n";
fs.writeFileSync(path.join(root, "src", "lib", "laravel-templates.generated.ts"), `${header}import type { LaravelTemplate } from "./laravel-templates";\n\nexport const GENERATED_TEMPLATES: LaravelTemplate[] = ${JSON.stringify(templates, null, 2)};\n`);
console.log(`laravel templates: ${templates.map((t) => t.id).join(", ")}`);
